import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { typedAbiSpecs, validateTypedAbiSpec } from "./typed-abi-spec.mjs";

const check = process.argv.includes("--check");
const definitionsFile = "definitions/win32/typed-abi.json";
const ids = JSON.parse(fs.readFileSync("definitions/metadata/id-assignments.json", "utf8"));
const definitions = [];
const wrappers = ["// Generated by tools/def-validator/generate-typed-abi.mjs."];
const metadata = [];
for (const spec of typedAbiSpecs)
{
  validateTypedAbiSpec(spec);
  const id = ids.apis.find((entry) => entry.module.toLowerCase() === spec.module && entry.name === spec.name);
  assert.ok(id, `Missing stable identity for ${spec.name}`);
  definitions.push({ module: spec.module, name: spec.name, ordinal: spec.ordinal, family: "typed_abi", category: "abi_verified_call",
    risk: "low", hookPolicy: "iat", coverageStatus: "hooked", architectures: ["x86", "x64"],
    callingConvention: "winapi", returnType: spec.returnType,
    errorSource: spec.returnType === "HRESULT" ? "HRESULT" : "none",
    parameters: spec.parameters.map(({ type, name, direction, kind }) => ({ type, name, direction,
      decode: kind === "Pointer" ? "pointer" : "abi_value_bits" })) });
  const argumentsText = spec.parameters.map(({ type, name }) => `${type} ${name}`).join(", ");
  wrappers.push(`decltype(&::${spec.name}) g_originalTyped${spec.name} = nullptr;`,
    `${spec.returnType} WINAPI HookedTyped${spec.name}(${argumentsText})`, "{",
    `    return InvokeTypedApi<${id.id}>(g_originalTyped${spec.name}, ${spec.parameters.map(({ name }) => name).join(", ")});`, "}",
    `static_assert(std::is_same_v<decltype(&HookedTyped${spec.name}), decltype(&::${spec.name})>, "Typed SDK ABI: ${spec.name}");`, "");
  metadata.push(`    { ${id.id}, "${spec.module}", "${spec.name}", TypedValueKind::${spec.returnKind}, ${spec.parameters.length}, { ${spec.parameters.map(({ kind }) => `TypedValueKind::${kind}`).join(", ")} } },`);
}
function output(file, value)
{
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replaceAll("\r\n", "\n") : "";
  if (check)
  {
    assert.equal(existing, value, `Stale typed ABI artifact: ${file}`);
  }
  else if (existing !== value)
  {
    fs.writeFileSync(file, value);
  }
}
// Promotion preserves stable IDs and removes the old imported/opaque declaration.
for (const name of fs.readdirSync("definitions/win32"))
{
  const file = path.join("definitions/win32", name).replaceAll("\\", "/");
  if (!name.endsWith(".json") || file === definitionsFile)
  {
    continue;
  }
  const document = JSON.parse(fs.readFileSync(file, "utf8"));
  const apis = document.apis.filter((api) => !typedAbiSpecs.some((spec) =>
    spec.module === api.module.toLowerCase() && spec.name === api.name));
  if (apis.length !== document.apis.length)
  {
    assert.equal(check, false, `Duplicate imported typed declaration: ${file}`);
    assert.ok(name.startsWith("generated-"), "Do not replace an authored definition implicitly.");
    output(file, `${JSON.stringify({ ...document, apis }, null, 2)}\n`);
  }
}
output(definitionsFile, `${JSON.stringify({ schemaVersion: "0.1.0", module: "typed_abi",
  description: "Compiler-bound SDK ABI contracts. Pointer pointees are not sampled by these wrappers.", apis: definitions }, null, 2)}\n`);
output("native/knmon-agent64/src/GeneratedTypedHooks.inc", wrappers.join("\n"));
output("native/knmon-common/include/knmon/common/GeneratedTypedAbi.h", [
  "// Generated by tools/def-validator/generate-typed-abi.mjs.", "#pragma once", "#include <cstdint>", "", "namespace knmon", "{",
  "enum class TypedValueKind : std::uint32_t", "{", "    Void, Unsigned32, Signed32, SignedPointer, Pointer, Float32, Float64, Point2F, Color4F", "};",
  "struct TypedAbiMetadata", "{", "    std::uint16_t Id;", "    const char* Module;", "    const char* Name;",
  "    TypedValueKind ReturnKind;", "    std::uint32_t ArgumentCount;", "    TypedValueKind Arguments[3];", "};",
  "inline constexpr TypedAbiMetadata TypedAbiContracts[] =", "{", ...metadata, "};",
  "inline const TypedAbiMetadata* FindTypedAbi(std::uint16_t id)", "{",
  "    const TypedAbiMetadata* result = nullptr;", "    for (const auto& entry : TypedAbiContracts)", "    {",
  "        if (entry.Id == id)", "        {", "            result = &entry;", "            break;", "        }", "    }", "    return result;", "}", "}", ""
].join("\n"));
console.log(`Typed ABI contracts: ${typedAbiSpecs.length}`);
